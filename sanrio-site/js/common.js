/* =====================================================
   common.js - 모든 페이지 공통 기능
   햄버거 버튼 클릭 시 메뉴 보이기/숨기기
   ===================================================== */
(function () {
  //1. 대상 선정
  //1-1. 이벤트 대상 : menu-btn (햄버거 버튼)
  const 햄버거 = document.querySelector(".menu-btn");
  //1-2. 변경 대상: 상단영역 .header-area
  const 상단박스 = document.querySelector(".header-area");

  //헤더/햄버거 버튼이 없는 페이지에서는 아무것도 실행하지 않음
  if (!햄버거 || !상단박스) return;

  //2. 이벤트 함수 만들기
  // 햄버거 클릭시 상단박스 클래스 on 넣기
  햄버거.onclick = () => {
    //classList 객체는 클래스를 넣고(.add('클래스명')) 빼는(.remove('클래스명')) 등의 기능을 가지고있음
    //toggle('클래스명')-클래스넣기빼기전환
    상단박스.classList.toggle("on");
  }; //-------------클릭 이벤트 함수----------------
})();
